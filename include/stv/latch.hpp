/// NAME
///     stv::latch
///
/// DESCRIPTION
///     stv::latch реализует одноразовую защелку (one-shot latch) для
///     обнаружения и однократного потребления событий. После получения
///     входного сигнала true защелка фиксируется в состоянии true и
///     остается в нем до первого вызова read(). Вызов read() возвращает
///     текущее состояние и автоматически сбрасывает защелку в false.
///
///     Основные методы:
///     - update(bool input): устанавливает защелку, если input равен
///       true и защелка еще не сработала. Повторные вызовы update(true)
///       не имеют эффекта, пока состояние не будет сброшено.
///     - read(): считывает состояние и атомарно сбрасывает защелку в
///       false. Это единственный способ вернуть защелку в исходное
///       состояние.
///     - explicit operator bool(): удобная проверка состояния.
///       Вызывает read(), поэтому также сбрасывает защелку.
///
///     Класс применяется для фиксации флагов готовности данных,
///     обнаружения единичных импульсов и управления прерываниями в
///     системах с ограниченными ресурсами.
///
///     Реализация не является потокобезопасной. При использовании в
///     многопоточной среде требуется внешняя синхронизация.
///
/// EXAMPLE
///     Пример использования защелки для обработки однократного
///     события:
///     ```cpp
///     #include <stv/latch.hpp>
///     #include <iostream>
///
///     int main() {
///         stv::latch data_ready;
///
///         // Сигнал пока не активен.
///         data_ready.update(false);
///         std::cout << "Ready? " << (data_ready ? "yes" : "no")
///                   << "\n";
///
///         // Произошло событие.
///         data_ready.update(true);
///         std::cout << "Ready? " << (data_ready ? "yes" : "no")
///                   << "\n";
///
///         // После чтения защелка сбрасывается.
///         std::cout << "Ready? " << (data_ready ? "yes" : "no")
///                   << "\n";
///
///         return 0;
///     }
///     ```
///     Вывод:
///     ```
///     Ready? no
///     Ready? yes
///     Ready? no
///     ```
///
///     См. test_latch.cpp для автоматизированных тестов.

#ifndef LATCH_HPP
#define LATCH_HPP

#include <utility>

namespace stv {

/// @brief Класс защелки (latch) — одноразовое событийное устройство.
///
/// Класс `latch` реализует поведение одноразовой защелки: при получении
/// входного сигнала `true` он фиксирует состояние в `true` и остается в
/// этом состоянии до первого вызова `read()`. После вызова `read()`
/// состояние автоматически сбрасывается в `false`. Последующие вызовы
/// `update(true)` не имеют эффекта, пока состояние не будет сброшено.
///
/// Используется для обнаружения и однократного потребления событий,
/// например:
/// - фиксации флага готовности данных
/// - обнаружения единичного импульса
/// - управления прерываниями в системах с ограниченными ресурсами
///
/// @note Класс не является потокобезопасным. Для использования в
/// многопоточной среде требуется внешняя синхронизация (например, через
/// `stv::lock_guard`).
///
/// @see stv::lock_guard, stv::empty_mutex
class latch
{
  private:
    /// @brief Текущее состояние защелки.
    /// - `false`: защелка не сработала
    /// - `true`: защелка сработала и ожидает сброса
    mutable bool latched_{false};

  public:
    /// @brief Неявное приведение к `bool` для удобства проверки
    /// состояния.
    ///
    /// Возвращает `true`, если защелка установлена (т.е. `read()` вернет
    /// `true`), и `false` в противном случае.
    ///
    /// @return `true`, если защелка активна, иначе `false`.
    explicit operator bool() const { return read(); }

    /// @brief Обновляет состояние защелки на основе входного сигнала.
    ///
    /// Если входное значение `input` равно `true` и защелка еще не была
    /// установлена, состояние защелки переходит в `true`. Если защелка
    /// уже установлена, вызов не имеет эффекта.
    ///
    /// @param[in] input Новое входное значение. Если `true` и защелка не
    /// установлена — защелка срабатывает. Если `false` — состояние не
    /// меняется.
    void update(
        bool input)
    {
        if(input)
        {
            latched_ = true;
        }
    }

    /// @brief Считывает текущее состояние защелки и сбрасывает его в
    /// `false`.
    ///
    /// Этот метод является единственным способом сбросить защелку. После
    /// вызова `read()` защелка возвращается в неактивное состояние
    /// (`false`), и может быть снова сработана только при последующем
    /// вызове `update(true)`.
    ///
    /// @return `true`, если защелка была установлена (т.е. до вызова
    /// `read()` значение было `true`), `false` в противном случае.
    ///
    /// @note Метод атомарно считывает и сбрасывает состояние, что делает
    /// его идеальным для обработки однократных событий без потерь.
    bool read() const { return std::exchange(latched_, false); }
};

} // namespace stv

#endif /* LATCH_HPP */
