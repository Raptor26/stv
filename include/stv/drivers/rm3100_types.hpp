/// @brief Базовый тип данных для регистров магнитометра PNI RM3100.
///
/// @details
///     Заголовок определяет псевдоним @ref stv::rm3100_reg_type — единый
///     8-битный тип, которым представляются адреса регистров и их значения
///     при обмене с датчиком по шине I2C. На этом типе построены все
///     регистровые классы из `rm3100_regs.hpp` (POLL, CMM, CCx, TMRC, STATUS,
///     BIST, REVID), низкоуровневый I2C-слой из `rm3100_i2c.hpp` и драйвер
///     @ref stv::rm3100.
///
///     Заголовок намеренно минимален: в нём нет ничего, кроме псевдонима
///     типа, поэтому его можно подключать без лишних зависимостей.

#ifndef RM3100_TYPES_HPP
#define RM3100_TYPES_HPP

#include <cstdint>

namespace stv {

/// @brief Тип данных для представления регистра RM3100.
///
/// @details
///     8-битное беззнаковое целое (@c std::uint8_t). Все регистры RM3100
///     имеют ширину один байт, поэтому тип используется как для адресов
///     регистров (например, @c 0x00 — POLL, @c 0x01 — CMM), так и для
///     передаваемых и принимаемых значений регистров.
///
///     Тип применяется:
///     - как тип константы @c addr в каждом регистровом классе (например,
///       @c rm3100_poll_reg::addr);
///     - как тип параметра конструктора и оператора преобразования
///       регистровых классов (упаковка и распаковка битовых полей в сырой
///       байт);
///     - как параметр шаблона @c Addr в @ref stv::rm3100_setup — 7-битный
///       I2C-адрес устройства (по умолчанию 0x20);
///     - как тип элементов буферов при чтении и записи по I2C в драйвере
///       @ref stv::rm3100.
///
/// @code
/// // Предполагается, что подключён заголовок rm3100_regs.hpp.
/// // Адрес регистра и его сырое значение имеют один и тот же тип.
/// stv::rm3100_cmm_reg cmm{};
/// cmm.start = true;
/// cmm.cmx   = true;
///
/// // Упаковка битовых полей в байт для передачи по I2C.
/// const stv::rm3100_reg_type raw = static_cast<stv::rm3100_reg_type>(cmm);
///
/// // Обратное преобразование: разбор байта, считанного из датчика.
/// const stv::rm3100_cmm_reg parsed{raw};
/// @endcode
using rm3100_reg_type = std::uint8_t;

} // namespace stv

#endif /* RM3100_TYPES_HPP */
