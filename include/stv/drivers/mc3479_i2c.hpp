/// @brief Обёртка для доступа к регистрам датчика MC3479 по шине I2C.
///
/// @details
/// Данный файл содержит:
/// - структуру конфигурации @ref stv::mc3479_i2c_setup, в которой задаётся
/// указатель на I2C-интерфейс
///   и 7-битный адрес устройства;
/// - класс @ref stv::mc3479_i2c — минимальный транспортный слой для
/// чтения/записи регистров MC3479.
///
/// Класс предоставляет два уровня API:
/// 1) Низкоуровневый: чтение/запись по адресу регистра (байтовый доступ).
/// 2) Типобезопасный: чтение/запись “типизированных” регистров (структуры/типы
/// из
///    `stv/drivers/mc3479_types.hpp`, которые должны иметь поле `addr` и
///    бинарно соответствовать формату регистра).
///
/// Особенность:
/// - При определённом флаге сборки может применяться разворот битов
///   (bit-reversal) при чтении/записи.
///   Это управляется макросом `MC3479_BITS_REVERS` (если определён и равен 1).
///   В таком режиме значения, отправляемые в устройство и читаемые из него,
///   проходят через `etl::reverse_bits()`.
///
/// Требования к использованию:
/// - Пользователь обязан передать валидный указатель `stv::i2c_interface*` в
///   настройках.
/// - Перед вызовами @ref stv::mc3479_i2c::read и @ref stv::mc3479_i2c::write
///   рекомендуется проверить объект через `if (dev)` (см. @ref
///   stv::mc3479_i2c::operator bool).

#ifndef MC3479_I2C_HPP
#define MC3479_I2C_HPP

#include "etl/binary.h"
#include "stv/drivers/mc3479_types.hpp"
#include "stv/i2c.hpp"
#include <cstring>

namespace stv {

/// @brief Параметры и константы для инициализации транспорта MC3479 по I2C.
///
/// @details
/// Структура используется для передачи параметров в конструктор @ref
/// stv::mc3479_i2c. Здесь же определены два типовых 7-битных I2C адреса MC3479,
/// зависящие от состояния вывода A6 (AD6):
/// - @ref i2c_addr_connect_to_gnd — когда A6 подключён к земле (GND);
/// - @ref i2c_addr_connect_to_vdd — когда A6 подключён к питанию (VDD).
///
/// Поля структуры:
/// - `i2c` — указатель на объект шины, реализующий @ref stv::i2c_interface;
/// - `i2c_addr` — 7-битный адрес устройства на шине (по умолчанию выбран адрес
///   для AD6=GND).
///
/// Примечание:
/// - Валидация указателя `i2c` выполняется пользователем (класс @ref
///   stv::mc3479_i2c допускает `nullptr`,
///   что отражается через @ref stv::mc3479_i2c::operator bool).
struct mc3479_i2c_setup {
    /// @brief I2C адрес устройства, когда вывод A6 подключен к земле (GND).
    ///
    /// @details
    /// Используется как значение по умолчанию для поля @ref i2c_addr.
    /// Значение является 7-битным адресом устройства (как принято в большинстве
    /// HAL/драйверов).
    static constexpr mc3479_reg_type i2c_addr_connect_to_gnd{0x4c};

    /// @brief I2C адрес устройства, когда вывод A6 подключен к питанию (VDD).
    ///
    /// @details
    /// Используйте этот адрес, если аппаратно вывод A6 (AD6) установлен в лог.1
    /// (VDD).
    static constexpr mc3479_reg_type i2c_addr_connect_to_vdd{0x6c};

    /// @brief Указатель на объект интерфейса шины I2C (i2c_interface).
    ///
    /// @details
    /// Должен указывать на живой объект, реализующий методы чтения/записи,
    /// совместимые с ожиданиями @ref stv::mc3479_i2c. Если оставить `nullptr`,
    /// объект @ref stv::mc3479_i2c будет считаться невалидным (см. @ref
    /// stv::mc3479_i2c::operator bool), а вызовы read/write приведут к
    /// неопределённому поведению (разыменование nullptr).
    stv::i2c_interface *i2c{nullptr};

    /// @brief Адрес устройства на шине I2C.
    ///
    /// @details
    /// По умолчанию используется адрес @ref i2c_addr_connect_to_gnd (AD6=GND).
    /// При необходимости установите в @ref i2c_addr_connect_to_vdd (AD6=VDD)
    /// или иной адрес, если это предусмотрено вашей аппаратной
    /// схемой/модификацией.
    mc3479_reg_type i2c_addr{i2c_addr_connect_to_gnd};
};

/// @brief Транспортный класс для работы с MC3479 по I2C.
///
/// @details
/// @ref stv::mc3479_i2c инкапсулирует обращение к регистрам устройства MC3479
/// через абстракцию
/// @ref stv::i2c_interface.
///
/// Ключевые возможности:
/// - чтение блока байтов из последовательных регистров (burst read);
/// - чтение одного байта регистра;
/// - запись одного байта регистра;
/// - чтение/запись типизированных регистров (структуры регистров), если в
///   проекте определены соответствующие типы (обычно в
///   `stv/drivers/mc3479_types.hpp`).
///
/// Типизированный доступ:
/// - Метод `read(const U& reg)` ожидает, что `reg` имеет поле `addr` (адрес
///   регистра), а бинарный размер типа `U` совпадает с размером регистра на
///   шине (обычно 1 байт). Значение читается как байт и затем копируется в `U`
///   через `std::memcpy`.
/// - Метод `write(U reg)` берёт экземпляр типизированного регистра, копирует
///   его байтовое
///   представление в `mc3479_reg_type` и записывает по адресу `reg.addr`.
///
/// Важные ограничения:
/// - Класс не владеет `i2c_interface`: ответственность за жизненный цикл
///   объекта I2C лежит на пользователе.
/// - Класс не выполняет проверок на `nullptr` перед каждой операцией (кроме
///   косвенной проверки через @ref operator bool), поэтому вызывающая сторона
///   должна гарантировать валидность.
class mc3479_i2c:
    public virtual stv::non_copyable,
    public virtual stv::non_movable
{
    /// @brief Указатель на интерфейс шины I2C.
    ///
    /// @details
    /// Хранится как `const stv::i2c_interface*`, так как класс не должен
    /// изменять состояние транспортного интерфейса (только вызывать операции
    /// передачи). Указатель не владеет классом, должен оставаться валидным
    /// всё время жизни @ref mc3479_i2c.
    const stv::i2c_interface *i2c_;

    /// @brief 7-битный адрес устройства на шине I2C.
    ///
    /// @details
    /// Адрес берётся из @ref stv::mc3479_i2c_setup::i2c_addr и фиксируется в
    /// объекте. Используется при каждом вызове чтения/записи.
    const mc3479_reg_type i2c_addr_;

    /// @brief Внутренняя функция для опционального разворота битов в байте.
    ///
    /// @tparam T Тип входного значения (ожидается целочисленный тип, приводимый
    /// к uint8_t).
    /// @param value Значение, которое требуется преобразовать.
    /// @return Значение, приведённое к @ref mc3479_reg_type; при активном
    /// `MC3479_BITS_REVERS==1`
    ///         возвращается результат `etl::reverse_bits(uint8_t(value))`,
    ///         иначе возвращается `value`.
    ///
    /// @details
    /// Некоторые аппаратные/протокольные конфигурации могут требовать изменения
    /// порядка битов (bit-reversal) для совместимости. Чтобы включить эту
    /// логику, определите макрос:
    /// `#define MC3479_BITS_REVERS 1`.
    /// Если макрос не определён или равен 0, функция работает как “identity”.
    template<typename T>
    [[nodiscard]] auto reverse_bits(
        T value) const
    {
#if defined(MC3479_BITS_REVERS) && (MC3479_BITS_REVERS == 1)
        return mc3479_reg_type{
            etl::reverse_bits(static_cast<std::uint8_t>(value))};
#else
        return mc3479_reg_type{value};
#endif
    }

  public:
    /// @brief Создаёт объект транспорта MC3479 по I2C с заданными параметрами.
    ///
    /// @param setup Конфигурация: указатель на I2C интерфейс и адрес
    /// устройства.
    ///
    /// @details
    /// Конструктор не выполняет активных проверок и не инициирует устройство.
    /// Он только сохраняет указатель `setup.i2c` и адрес `setup.i2c_addr`.
    /// Для проверки корректности конфигурации используйте @ref operator bool.
    explicit mc3479_i2c(
        const mc3479_i2c_setup &setup):
        i2c_{setup.i2c},
        i2c_addr_{setup.i2c_addr}
    {
    }

    /// @brief Виртуальный деструктор.
    ///
    /// @details
    /// Класс не владеет ресурсами и не освобождает `i2c_`.
    virtual ~mc3479_i2c() = default;

    /// @brief Проверка валидности настроек транспорта.
    ///
    /// @return `true`, если в объекте задан ненулевой указатель на I2C
    /// интерфейс; иначе `false`.
    ///
    /// @details
    /// Используйте эту проверку перед обращением к устройству:
    /// @code{.cpp}
    /// if (!dev) { /* i2c не задан */ }
    /// @endcode
    virtual explicit operator bool() const { return i2c_ != nullptr; }

    /// @brief Чтение последовательности байтов из регистров устройства (burst
    /// read).
    ///
    /// @param reg_addr Адрес начального регистра для чтения.
    /// @param dst Указатель на буфер в памяти пользователя, куда будут записаны
    /// данные.
    /// @param len Количество байтов для чтения.
    /// @return Результат операции чтения (зависит от реализации @ref
    /// stv::i2c_interface).
    ///
    /// @details
    /// Выполняет чтение `len` байтов, начиная с `reg_addr`, и помещает их в
    /// буфер `dst`. Данный метод полезен для чтения многобайтовых блоков
    /// данных, например измерений, которые занимают несколько последовательных
    /// регистров.
    ///
    /// Важно:
    /// - `dst` должен указывать на валидный участок памяти размером не меньше
    /// `len`.
    /// - Метод не выполняет разворот битов для каждого байта блока: он
    ///   делегирует чтение напрямую в `i2c_interface`. Если вам нужен
    ///   bit-reversal для каждого байта блока, сделайте постобработку на
    ///   стороне пользователя или расширьте реализацию.
    auto read(
        mc3479_reg_type reg_addr, void *dst, std::size_t len) const
    { return i2c_->read(i2c_addr_, reg_addr, dst, len); }

    /// @brief Чтение одного регистра (1 байт) по указанному адресу.
    ///
    /// @param reg_addr Адрес регистра.
    /// @return Считанное значение регистра (с учётом опционального
    /// bit-reversal).
    ///
    /// @details
    /// Метод читает ровно один байт в локальную переменную, затем (при
    /// необходимости) применяет @ref reverse_bits и возвращает результат.
    ///
    /// Пример:
    /// @code{.cpp}
    /// auto val = dev.read(static_cast<mc3479_reg_type>(0x10));
    /// @endcode
    [[nodiscard]] auto read(
        mc3479_reg_type reg_addr) const
    {
        mc3479_reg_type reg_val{0xFF};
        read(reg_addr, &reg_val, sizeof(reg_val));
        return reverse_bits(reg_val);
    }

    /// @brief Чтение типизированного регистра.
    ///
    /// @tparam U Тип регистра (обычно структура/обёртка из `mc3479_types.hpp`).
    /// @param reg Объект-описатель регистра, должен содержать поле `addr` с
    /// адресом регистра.
    /// @return Экземпляр типа `U`, заполненный считанными данными.
    ///
    /// @details
    /// Этот метод предназначен для удобного чтения регистров, описанных
    /// пользовательскими типами. Алгоритм: 1) читается байт по адресу
    /// `reg.addr` через @ref read(mc3479_reg_type); 2) затем байт побайтно
    /// копируется в переменную типа `U` через `std::memcpy`.
    ///
    /// Ограничения и предположения:
    /// - Размер `U` должен совпадать с размером читаемых данных (здесь читается
    /// 1 байт).
    /// - Тип `U` должен быть тривиально копируемым (trivially copyable), иначе
    /// копирование
    ///   через `memcpy` может быть некорректным.
    ///
    /// Пример (условный):
    /// @code{.cpp}
    /// // Пусть mc3479_reg_ctrl имеет поле addr и битовые поля конфигурации
    /// auto ctrl = dev.read(stv::mc3479_reg_ctrl{});
    /// if (ctrl.some_flag) { ... }
    /// @endcode
    template<typename U>
    [[nodiscard]] auto read(
        U reg) const
    {
        static_assert(sizeof(U) == 1, "Register size must be equal to 1");
        auto read_val = read(reg.addr);
        U    typed_val;
        std::memcpy(reinterpret_cast<void *>(&typed_val),
                    reinterpret_cast<const void *>(&read_val),
                    sizeof(typed_val));
        return typed_val;
    }

    /// @brief Запись одного байта в указанный регистр устройства.
    ///
    /// @param reg_addr Адрес регистра для записи.
    /// @param value Значение для записи в регистр.
    /// @return Результат операции записи (зависит от реализации @ref
    /// stv::i2c_interface).
    ///
    /// @details
    /// Перед отправкой `value` может быть преобразовано функцией @ref
    /// reverse_bits (если активирован `MC3479_BITS_REVERS==1`).
    ///
    /// Пример:
    /// @code{.cpp}
    /// dev.write(static_cast<mc3479_reg_type>(0x10),
    /// static_cast<mc3479_reg_type>(0x01));
    /// @endcode
    auto write(
        mc3479_reg_type reg_addr, mc3479_reg_type value)
    { return i2c_->write(i2c_addr_, reg_addr, reverse_bits(value)); }

    /// @brief Запись типизированного регистра.
    ///
    /// @tparam U Тип регистра (обычно структура/обёртка из `mc3479_types.hpp`).
    /// @param reg Экземпляр типизированного регистра, должен содержать поле
    /// `addr`.
    ///
    /// @details
    /// Метод копирует байтовое представление `reg` в переменную типа @ref
    /// mc3479_reg_type (обычно 1 байт), затем записывает по адресу `reg.addr`
    /// через @ref write(mc3479_reg_type, mc3479_reg_type).
    ///
    /// Рекомендации:
    /// - Передавайте `reg` как сконфигурированную структуру с нужными битовыми
    ///   полями.
    /// - Убедитесь, что размер `U` соответствует ожидаемому размеру регистра (1
    ///   байт), иначе копирование будет некорректным.
    ///
    /// Пример (условный):
    /// @code{.cpp}
    /// stv::mc3479_reg_ctrl ctrl{};
    /// ctrl.addr = ...;          // обычно addr задан константно внутри
    /// типа/объекта ctrl.some_flag = 1; dev.write(ctrl);
    /// @endcode
    template<typename U>
    auto write(
        U reg)
    {
        static_assert(sizeof(U) == 1, "Register size must be equal to 1");
        mc3479_reg_type reg_val{};
        std::memcpy(reinterpret_cast<void *>(&reg_val),
                    reinterpret_cast<const void *>(&reg), sizeof(reg_val));
        write(reg.addr, reg_val);
    }
};

} // namespace stv

#endif /* MC3479_I2C_HPP */
